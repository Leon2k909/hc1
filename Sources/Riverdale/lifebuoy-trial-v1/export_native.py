"""Export the approved editable model to Source-compatible inch OBJ axes and LODs."""
from pathlib import Path
import bpy,json,shutil
ROOT=Path.cwd();HERE=ROOT/'Sources/Riverdale/lifebuoy-trial-v1'
STAGE=ROOT/'output/asset-improvement-20261031/riverdale-lifebuoy/install-stage'
MODELS=STAGE/'Assets/models/maps/riverdale/lifebuoy_v2';MATS=STAGE/'Assets/materials/riverdale/lifebuoy_v2'
MODELS.mkdir(parents=True,exist_ok=True);MATS.mkdir(parents=True,exist_ok=True)
names={'Moulded orange buoy shell':'orange','White reflective band fabric':'white',
       'Three strand floating grab rope':'rope','Brushed stainless mounting hardware':'steel',
       'Neoprene contact pads and hook sleeve':'rubber','Woven rope retention loops':'webbing'}
bpy.ops.wm.open_mainfile(filepath=str(HERE/'lifebuoy_review.blend'))
bpy.ops.object.select_all(action='DESELECT')
parts=[o for o in bpy.context.scene.objects if o.type=='MESH' and not o.hide_render and not o.name.startswith('Same ')]
assert parts and all(m.name in names for o in parts for m in o.data.materials)
for o in parts:o.hide_set(False);o.select_set(True)
bpy.context.view_layer.objects.active=parts[0];bpy.ops.object.join();base=bpy.context.object
bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)

def export(o,path):
    mesh=o.data;mesh.calc_loop_triangles();uv=mesh.uv_layers.active.data
    # Local preview (right, back, up) -> OBJ (right, up, front).
    # In native model space +X faces out, +Y is the front-view right, +Z up.
    vector=lambda p:(p.x,p.z,-p.y)
    lines=['# Approved lifebuoy; inches, Source OBJ (world Y,Z,X)\n','mtllib lifebuoy.mtl\n']
    for v in mesh.vertices:lines.append('v '+' '.join(f'{c/.0254:.7f}' for c in vector(v.co))+'\n')
    for l in mesh.loops:lines.append('vt '+' '.join(f'{c:.7f}' for c in uv[l.index].uv)+'\n')
    for n in mesh.corner_normals:lines.append('vn '+' '.join(f'{c:.7f}' for c in vector(n.vector))+'\n')
    paint=None
    for tri in mesh.loop_triangles:
        material='rv_lb_'+names[o.data.materials[tri.material_index].name]
        if material!=paint:lines.append('usemtl '+material+'\n');paint=material
        assert tri.area>1e-14
        lines.append('f '+' '.join(f'{mesh.loops[li].vertex_index+1}/{li+1}/{li+1}' for li in tri.loops)+'\n')
    path.write_text(''.join(lines));return len(mesh.loop_triangles)

report=[]
for level,ratio in enumerate((1,.22,.045)):
    o=base.copy();o.data=base.data.copy();bpy.context.collection.objects.link(o);bpy.context.view_layer.objects.active=o
    if level:
        mod=o.modifiers.new('Distance LOD','DECIMATE');mod.ratio=ratio;mod.use_collapse_triangulate=True
        bpy.ops.object.modifier_apply(modifier=mod.name)
    count=export(o,MODELS/f'lifebuoy_lod{level}.obj');report.append({'lod':level,'triangles':count})
    bpy.data.objects.remove(o,do_unlink=True)
assert report[0]['triangles']==42468 and report[0]['triangles']>report[1]['triangles']>report[2]['triangles']
(MODELS/'lifebuoy.mtl').write_text(''.join(f'newmtl rv_lb_{p}\nKd 1 1 1\nd 1\n' for p in names.values()))
for prefix in names.values():
    for suffix in ('color','roughness','metallic','normal'):
        shutil.copy2(HERE/'textures'/f'{prefix}_{suffix}.png',MATS/f'{prefix}_{suffix}.png')
    material='''"Layer0"
{
    shader "shaders/complex.shader"
    F_SPECULAR "1"
    F_METALNESS_TEXTURE "1"
    g_flRoughnessScaleFactor "1"
    g_flMetalness "1"
    g_flModelTintAmount "1"
    g_vColorTint "[1 1 1 1]"
'''
    for key,suffix in [('Color','color'),('Normal','normal'),('Roughness','roughness'),('Metalness','metallic')]:
        material+=f'    Texture{key} "materials/riverdale/lifebuoy_v2/{prefix}_{suffix}.png"\n'
    material+='    TextureAmbientOcclusion "[1 1 1 1]"\n}\n'
    (MATS/f'rv_lb_{prefix}.vmat').write_text(material)
template=(ROOT/'Assets/models/maps/riverdale/eyewash_v2/eyewash.vmdl').read_text()
template=template.replace('// Generated by Sources/Riverdale/eyewash_v2/eyewash.py','// Approved lifebuoy, Sources/Riverdale/lifebuoy-trial-v1/export_native.py')
old='{ from = "eyewash.vmat" to = "models/maps/riverdale/eyewash_v2/eyewash.vmat" }'
remaps=',\n\t\t\t\t\t\t\t'.join(f'{{ from = "rv_lb_{p}.vmat" to = "materials/riverdale/lifebuoy_v2/rv_lb_{p}.vmat" }}' for p in names.values())
assert template.count(old)==1;template=template.replace(old,remaps).replace('models/maps/riverdale/eyewash_v2/eyewash_lod','models/maps/riverdale/lifebuoy_v2/lifebuoy_lod')
(MODELS/'lifebuoy.vmdl').write_text(template)
(STAGE.parent/'native-export.json').write_text(json.dumps({'lods':report,'source':'approved review blend','units':'inches','nativeForward':'+X','nativeUp':'+Z','materials':6},indent=2))
print(json.dumps(report))
