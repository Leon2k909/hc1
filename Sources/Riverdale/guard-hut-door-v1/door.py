"""Riverdale's spawn-yard guard hut door: the v2 hut's steel door (approved by the user on its own: "door is better") made surface-mounted for the original concrete huts.

python -X utf8 door.py [out dir]    writes Assets/models/props/riverdale/guard_hut_door_v1/ (guard_hut_door.vmdl, three LODs)

Replaces P.door( m, ..., 36, 82, paint="rv_fc_door_blue", double=False, mount="surface" ) in riverdale_map.guard_hut(). A dark steel frame standing 2 in off the wall, a blue
steel leaf inside it with a wired vision panel (the map's control-room glass), kick plate, lever handle with rose, lock cylinder, three hinge barrels, an overhead closer and a PPE sign.
Origin: the door's centre at its foot on the wall face; the wall is the plane y = 0 and the door looks along +y (plan axes, x along the wall). Render only, as the old door was.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "Tools"))
import map_kit as K  # noqa: E402
import riverdale_materials as RM  # noqa: E402
import riverdale_parts as G  # noqa: E402
import riverdale_yard as RY  # noqa: E402

OUT = ROOT / "Assets" / "models" / "props" / "riverdale" / "guard_hut_door_v1"
RESOURCE_DIR = "models/props/riverdale/guard_hut_door_v1"
NAME = "guard_hut_door"
LOD_THRESHOLDS = (0.0, 30.0, 80.0)
X = np.array((1.0, 0.0, 0.0))
Y = np.array((0.0, 1.0, 0.0))
Z = np.array((0.0, 0.0, 1.0))
W, H = 36.0, 82.0
FW = 1.8            # frame width
FD = 2.0            # frame depth off the wall
SD = 1.3            # leaf front off the wall
GLASS = "rw_glass"
PATHS = {GLASS: "materials/railhead/rw_glass.vmat"}


def build(lod=0):
    m = K.Model()
    d0, d1 = lod == 0, lod <= 1

    def box(x0, x1, z0, z1, y0, y1, paint, bevel=0.0, skip=()):
        G.bevel_box(m, ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2), (X, Y, Z), (x1 - x0, y1 - y0, z1 - z0), paint, bevel=bevel if d0 else 0.0, skip=skip)

    def rod(a, b, r, paint, sides=8):
        G.rod(m, a, b, r, paint, sides, caps=True)

    back = ("-y",)
    # Frame: two jambs and a head, and the leaf.
    box(-W / 2 - FW, -W / 2, 0.0, H + FW, 0.0, FD, "rv_dark", 0.3, back)
    box(W / 2, W / 2 + FW, 0.0, H + FW, 0.0, FD, "rv_dark", 0.3, back)
    box(-W / 2, W / 2, H, H + FW, 0.0, FD, "rv_dark", 0.3, back)
    box(-W / 2 + 0.2, W / 2 - 0.2, 0.4, H - 0.2, 0.0, SD, "rv_fc_door_blue", 0.3, back)
    vz0, vz1 = 52.0, 74.0
    if d1:
        box(-5.0, 5.0, vz0, vz1, SD - 0.05, SD + 0.35, "rv_dark", 0.15, back)
        box(-3.8, 3.8, vz0 + 1.2, vz1 - 1.2, SD + 0.25, SD + 0.37, GLASS)
        box(-W / 2 + 1.0, W / 2 - 1.0, 1.0, 11.0, SD - 0.05, SD + 0.2, "rv_stainless", 0.1, back)
    if d0:
        for zz in (vz0 + 5.0, vz0 + 11.0, vz0 + 17.0):
            box(-3.8, 3.8, zz - 0.06, zz + 0.06, SD + 0.38, SD + 0.44, "rv_steel")
        hz, hx = 38.0, W / 2 - 4.0
        rod((hx, SD - 0.05, hz), (hx, SD + 1.4, hz), 1.3, "rv_stainless", 10)
        rod((hx, SD + 1.4, hz), (hx - 6.0, SD + 1.4, hz), 0.5, "rv_stainless", 6)
        rod((hx, SD - 0.05, hz - 5.0), (hx, SD + 0.8, hz - 5.0), 0.8, "rv_stainless", 8)
        for zz in (12.0, 41.0, 70.0):
            rod((-W / 2 + 0.6, SD + 1.0, zz - 2.5), (-W / 2 + 0.6, SD + 1.0, zz + 2.5), 0.75, "rv_galv", 8)
        box(2.0, 11.0, H - 5.0, H - 2.0, SD - 0.05, SD + 2.4, "rv_steel", 0.3, back)                        # closer
        rod((3.0, SD + 2.4, H - 3.5), (-7.0, FD + 1.2, H + 0.8), 0.45, "rv_steel", 4)
        uv = [RM.atlas_uv(RY.SIGNS, RY.SIGN_ATLAS, "ppe", s, t) for s, t in ((0, 0), (1, 0), (1, 1), (0, 1))]
        G.quad(m, "rv_yd_signs", (0.0, SD + 0.02, 45.0), -X, Z, 9.0, 6.0, uv)
    for paint in m.polygons:
        m.material_overrides[paint] = PATHS.get(paint, f"{RM.RESOURCE_DIR}/{paint}.vmat")
        m.tile_overrides[paint] = RM.TILES.get(paint, 64.0)
    return m


def vmdl_text(paints):
    remaps = ",\n".join(f'\t\t\t\t\t\t\t{{ from = "{p}.vmat" to = "{PATHS.get(p, RM.RESOURCE_DIR + "/" + p + ".vmat")}" }}' for p in sorted(paints))
    meshes = ",\n".join(
        f'\t\t\t\t\t{{ _class = "RenderMeshFile" name = "lod{k}" filename = "{RESOURCE_DIR}/{NAME}_lod{k}.obj" import_translation = [ 0.0, 0.0, 0.0 ] '
        'import_rotation = [ 0.0, 0.0, 0.0 ] import_scale = 1.0 align_origin_x_type = "None" align_origin_y_type = "None" '
        'align_origin_z_type = "None" parent_bone = "" import_filter = { exclude_by_default = false exception_list = [ ] } }'
        for k in range(3))
    groups = ",\n".join(f'\t\t\t\t\t{{ _class = "LODGroup" switch_threshold = {t:.1f} meshes = [ "lod{k}" ] }}' for k, t in enumerate(LOD_THRESHOLDS))
    return ("<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} format:modeldoc29:version{3cec427c-1b0e-4d48-a90a-0436f33a6041} -->\n"
            "// Generated by Sources/Riverdale/guard-hut-door-v1/door.py\n"
            "{\n\trootNode =\n\t{\n\t\t_class = \"RootNode\"\n\t\tchildren =\n\t\t[\n"
            "\t\t\t{\n\t\t\t\t_class = \"MaterialGroupList\"\n\t\t\t\tchildren =\n\t\t\t\t[\n\t\t\t\t\t{\n\t\t\t\t\t\t_class = \"DefaultMaterialGroup\"\n"
            "\t\t\t\t\t\tremaps =\n\t\t\t\t\t\t[\n" + remaps + "\n\t\t\t\t\t\t]\n"
            "\t\t\t\t\t\tuse_global_default = false\n\t\t\t\t\t\tglobal_default_material = \"\"\n\t\t\t\t\t},\n\t\t\t\t]\n\t\t\t},\n"
            "\t\t\t{\n\t\t\t\t_class = \"RenderMeshList\"\n\t\t\t\tchildren =\n\t\t\t\t[\n" + meshes + "\n\t\t\t\t]\n\t\t\t},\n"
            "\t\t\t{\n\t\t\t\t_class = \"LODGroupList\"\n\t\t\t\tchildren =\n\t\t\t\t[\n" + groups + "\n\t\t\t\t]\n\t\t\t},\n"
            "\t\t]\n\t\tmodel_archetype = \"\"\n\t\tprimary_associated_entity = \"\"\n\t\tanim_graph_name = \"\"\n\t\tbase_model_name = \"\"\n\t}\n}\n")


def write_all(out=OUT):
    out.mkdir(parents=True, exist_ok=True)
    paints, tris = set(), []
    for lod in range(3):
        model = build(lod)
        model.uv_source_name = NAME
        tris.append(K.write_obj(out / f"{NAME}_lod{lod}.obj", model, NAME))
        paints |= set(model.polygons)
    K.write_text(out / f"{NAME}.vmdl", vmdl_text(paints))
    return tris


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    print(NAME, "triangles by LOD", write_all(target), "->", target)
