THRESHOLDS = (0.0, 24.0, 60.0, 150.0)


def uv_hash(ob):
    """Identifies the hardware's UV layout, which the bakes and so all the painted maps belong to."""
    data = np.empty(len(ob.data.loops) * 2, np.float32)
    ob.data.uv_layers["UVMap"].data.foreach_get("uv", data)
    return hashlib.sha1(data.tobytes()).hexdigest()


# Rerunning build.py can change the unwrap, and then the painted maps no longer fit: bake and paint again before this.
baked = open(os.path.join(WORK, "baked_uv_hash.txt")).read().strip()
if uv_hash(bpy.data.objects["hw_lod0"]) != baked:
    raise SystemExit("The build's UVs are not the ones the textures were baked on. Run bake.py and paint.py first.")


def finish_normals(ob):
    """Hard surface takes face-weighted normals across its bevels. Cloth, rope and bags are simply smooth."""
    mesh = ob.data
    mesh.polygons.foreach_set("use_smooth", np.ones(len(mesh.polygons), bool))
    if ob.name.startswith("hw"):
        mesh.set_sharp_from_angle(angle=math.radians(62))
        mod = ob.modifiers.new("wn", "WEIGHTED_NORMAL")
        mod.mode = "FACE_AREA"
        mod.weight = 100
        mod.keep_sharp = True
        mod.thresh = 0.01


def triangles(ob):
    """Positions, UVs and corner normals of each triangle after modifiers."""
    dg = bpy.context.evaluated_depsgraph_get()
    e = ob.evaluated_get(dg)
    mesh = e.to_mesh()
    mesh.calc_loop_triangles()
    n_loops = len(mesh.loops)
    n_tris = len(mesh.loop_triangles)
    loops = np.empty(n_tris * 3, np.int32)
    mesh.loop_triangles.foreach_get("loops", loops)
    verts = np.empty(n_loops, np.int32)
    mesh.loops.foreach_get("vertex_index", verts)
    co = np.empty(len(mesh.vertices) * 3, np.float64)
    mesh.vertices.foreach_get("co", co)
    co = co.reshape(-1, 3)
    uv = np.empty(n_loops * 2, np.float64)
    mesh.uv_layers["UVMap"].data.foreach_get("uv", uv)
    uv = uv.reshape(-1, 2)
    normals = np.empty(n_loops * 3, np.float64)
    mesh.corner_normals.foreach_get("vector", normals)
    normals = normals.reshape(-1, 3)
    p = co[verts[loops]].reshape(-1, 3, 3)
    t = uv[loops].reshape(-1, 3, 2)
    n = normals[loops].reshape(-1, 3, 3)
    e.to_mesh_clear()
    return p, t, n


def write_obj(path, sections, mtl):
    """sections: [(material, p, t, n)]. Vertices are deduplicated, so the file stays a real indexed mesh."""
    with open(path, "w", newline="\n") as h:
        h.write(f"# Generated by Sources/Gameplay/capture-flag-v2/export.py\nmtllib {mtl}\n")
        p_index, t_index, n_index = {}, {}, {}
        p_lines, t_lines, n_lines, face_lines = [], [], [], []

        def key_index(table, lines, prefix, values):
            key = tuple(np.round(values, 5))
            got = table.get(key)
            if got is None:
                got = len(table) + 1
                table[key] = got
                lines.append(prefix + " ".join(f"{v:.5f}" for v in key) + "\n")
            return got

        tris = 0
        for name, p, t, n in sections:
            face_lines.append(f"usemtl {name}\n")
            # Engine X, Y, Z become OBJ Z, X, Y: a rotation, so the winding holds.
            po = p[..., [1, 2, 0]]
            no = n[..., [1, 2, 0]]
            for k in range(len(po)):
                a = []
                for c in range(3):
                    a.append(
                        "%d/%d/%d"
                        % (
                            key_index(p_index, p_lines, "v ", po[k, c]),
                            key_index(t_index, t_lines, "vt ", t[k, c]),
                            key_index(n_index, n_lines, "vn ", no[k, c]),
                        )
                    )
                face_lines.append("f " + " ".join(a) + "\n")
            tris += len(po)
        h.writelines(p_lines)
        h.writelines(t_lines)
        h.writelines(n_lines)
        h.writelines(face_lines)
    return tris


for ob in bpy.data.objects:
    if ob.type == "MESH":
        finish_normals(ob)

counts = {}
bounds = None
for lod, names in LODS.items():
    sections = []
    for name in names:
        if not name:
            continue
        ob = bpy.data.objects[name]
        p, t, n = triangles(ob)
        sections.append((PAINTS[name.split("_")[0]], p, t, n))
        low, high = p.reshape(-1, 3).min(0), p.reshape(-1, 3).max(0)
        if lod == 0:
            bounds = (low, high) if bounds is None else (np.minimum(bounds[0], low), np.maximum(bounds[1], high))
    counts[lod] = write_obj(os.path.join(OUT, f"capture_flag_lod{lod}.obj"), sections, "capture_flag.mtl")
    print("lod", lod, "tris", counts[lod], flush=True)

with open(os.path.join(OUT, "capture_flag.mtl"), "w", newline="\n") as h:
    for name in PAINTS.values():
        h.write(f"newmtl {name}\nKd 1 1 1\nd 1\n")

remaps = ",\n".join(f'\t\t\t\t\t\t\t{{ from = "{m}.vmat" to = "{MATS}/{m}.vmat" }}' for m in PAINTS.values())
