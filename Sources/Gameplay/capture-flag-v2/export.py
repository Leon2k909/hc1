def vmat(name, tint, metal=True, ao=True, extra="", rough_scale="1.000"):
    lines = [
        "// Generated by Sources/Gameplay/capture-flag-v2/export.py",
        "",
        "Layer0",
        "{",
        '\tshader "shaders/complex.shader"',
        "",
        "\t//---- PBR ----",
    ]
    if metal:
        lines.append("\tF_METALNESS_TEXTURE 1")
    lines += ["\tF_SPECULAR 1"]
    if extra:
        lines.append(extra)
    lines += ["", "\t//---- Ambient Occlusion ----"]
    if ao:
        lines += [
            '\tg_flAmbientOcclusionDirectDiffuse "0.300"',
            '\tg_flAmbientOcclusionDirectSpecular "0.500"',
            f'\tTextureAmbientOcclusion "{MATS}/{name}_ao.png"',
        ]
    else:
        lines.append('\tTextureAmbientOcclusion "materials/default/default_ao.tga"')
    lines += [
        "",
        "\t//---- Color ----",
        f'\tg_flModelTintAmount "{tint:.3f}"',
        '\tg_vColorTint "[1.000000 1.000000 1.000000 0.000000]"',
        f'\tTextureColor "{MATS}/{name}_color.png"',
        "",
        "\t//---- Fog ----",
        '\tg_bFogEnabled "1"',
        "",
        "\t//---- Metalness ----",
    ]
    if metal:
        lines.append(f'\tTextureMetalness "{MATS}/{name}_metal.png"')
    else:
        lines.append('\tg_flMetalness "0.000"')
    lines += [
        "",
        "\t//---- Normal ----",
        f'\tTextureNormal "{MATS}/{name}_normal.png"',
        "",
        "\t//---- Roughness ----",
        f'\tg_flRoughnessScaleFactor "{rough_scale}"',
        f'\tTextureRoughness "{MATS}/{name}_rough.png"',
        "}",
        "",
    ]
    with open(os.path.join(MAT_OUT, name + ".vmat"), "w", newline="\n") as h:
        h.write("\n".join(lines))


