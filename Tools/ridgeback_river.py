"""Fit shallow river water to Ridgeback's CURRENT terrain; never regenerate the terrain.

In the running Ridgeback scene, run ridgeback_river_export in the editor console.
Then run: python Tools/ridgeback_river.py
Reload Ridgeback to see the result. Replaces only the River scene group. Terrain,
roads, buildings, scatter, collision and navigation data are preserved.
The export is a little-endian ushort heightmap plus terrain-info.json in output/river.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter1d, map_coordinates
import ridgeback_map as R

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "output/river"
RESOURCE = "models/maps/ridgeback/river"
MODEL_DIR = ROOT / "Assets" / RESOURCE
MATERIAL = "materials/water/ridgeback_river.vmat"


def write_model(name, points, distance, normals, surface):
    origin = np.r_[points[len(points) // 2], surface[len(points) // 2]]
    offsets = np.linspace(-620.0, 620.0, 9)
    lines = [f"# Generated by Tools/ridgeback_river.py", f"mtllib {name}.mtl", f"o {name}"]
    for p, normal, z in zip(points, normals, surface):
        for offset in offsets:
            v = np.r_[p + normal * offset, z] - origin
            lines.append(f"v {v[1]:.5f} {v[2]:.5f} {v[0]:.5f}")
    for d in distance:
        for offset in offsets:
            lines.append(f"vt {offset / 180:.6f} {d / 180:.6f}")
    lines += ["vn 0 1 0", "usemtl river"]
    # tangent x left -> right, tangent y downstream; CCW in world XY.
    for j in range(len(points) - 1):
        for k in range(len(offsets) - 1):
            a = j * len(offsets) + k + 1
            b, c, d = a + 1, a + len(offsets), a + len(offsets) + 1
            lines += [f"f {a}/{a}/1 {c}/{c}/1 {b}/{b}/1", f"f {b}/{b}/1 {c}/{c}/1 {d}/{d}/1"]
    (MODEL_DIR / f"{name}.obj").write_text("\n".join(lines) + "\n")
    (MODEL_DIR / f"{name}.mtl").write_text("newmtl river\nKd 1 1 1\nd 1\n")
    model = '''<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} format:modeldoc29:version{3cec427c-1b0e-4d48-a90a-0436f33a6041} -->
{
    rootNode = {
        _class = "RootNode"
        children = [
            { _class = "MaterialGroupList" children = [
                { _class = "DefaultMaterialGroup"
                  remaps = [ { from = "river.vmat" to = "%MATERIAL%" } ]
                  use_global_default = true global_default_material = "%MATERIAL%" }
            ] },
            { _class = "RenderMeshList" children = [
                { _class = "RenderMeshFile" name = "%NAME%" filename = "%RESOURCE%/%NAME%.obj"
                  import_translation = [ 0, 0, 0 ] import_rotation = [ 0, 0, 0 ] import_scale = 1
                  align_origin_x_type = "None" align_origin_y_type = "None" align_origin_z_type = "None"
                  parent_bone = "" import_filter = { exclude_by_default = false exception_list = [ ] } }
            ] }
        ]
        model_archetype = "" primary_associated_entity = "" anim_graph_name = "" base_model_name = ""
    }
}
'''.replace("%NAME%", name).replace("%RESOURCE%", RESOURCE).replace("%MATERIAL%", MATERIAL)
    (MODEL_DIR / f"{name}.vmdl").write_text(model)
    return R.game_object(name.replace("_", " ").title(), f"river/{name}", position=origin,
        components=[{"__type": "Sandbox.ModelRenderer", "__guid": R.gid(f"river/{name}/renderer"),
            "__enabled": True, "Model": f"{RESOURCE}/{name}.vmdl", "RenderType": "Off",
            "Tint": "1,1,1,1"}], tags="water")


def main():
    info = json.loads((OUT / "terrain-info.json").read_text())
    raw = (OUT / "terrain-heights.bin").read_bytes()
    height = np.frombuffer(raw, dtype="<u2").reshape(info["resolution"], info["resolution"])
    height = height.astype(float) * info["height"] / 65535 + info["z"]
    cell = info["size"] / info["resolution"]
    def sample(points):
        return map_coordinates(height, [(points[..., 1] - info["y"]) / cell - .5,
                                        (points[..., 0] - info["x"]) / cell - .5], order=1, mode="nearest")
    points = R.catmull_rom(R.RIVER, step=45)
    # Ends lie outside the playable boundary, so no visible cut across the water.
    points = points[np.max(np.abs(points), axis=1) < info["size"] / 2 + 100]
    distance = np.r_[0, np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))]
    tangent = np.gradient(points, axis=0)
    tangent /= np.linalg.norm(tangent, axis=1)[:, None]
    normals = np.column_stack((-tangent[:, 1], tangent[:, 0]))
    bed = sample(points)
    surface = np.clip(gaussian_filter1d(bed, 2) + 30, bed + 22, bed + 38)
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    children = []
    for number, start in enumerate(range(0, len(points) - 1, 70)):
        s = slice(start, min(start + 71, len(points)))
        children.append(write_model(f"river_{number:02}", points[s], distance[s], normals[s], surface[s]))
    scene_path = ROOT / "Assets/scenes/maps/Ridgeback/ridgeback.scene"
    original = scene_path.read_bytes()
    scene = json.loads(original)
    group = R.game_object("River", "river", children=children, tags="water")
    others = [obj for obj in scene["GameObjects"] if obj.get("__guid") != group["__guid"]]
    scene["GameObjects"] = others + [group]
    newline = "\r\n" if b"\r\n" in original else "\n"
    scene_path.write_bytes((json.dumps(scene, indent=2, ensure_ascii=False).replace("\n", newline) + newline).encode())
    check = json.loads(scene_path.read_bytes())
    assert check["GameObjects"][:-1] == others, "Unrelated scene objects changed"
    assert not any(c.get("__type", "").endswith("Collider") for o in children for c in o["Components"])
    report = {"sections": len(children), "length_units": round(float(distance[-1])),
              "center_depth_units": [round(float(np.min(surface-bed)), 1), round(float(np.max(surface-bed)), 1)],
              "terrain_sha256": hashlib.sha256(raw).hexdigest(),
              "samples": [{"x": round(float(p[0])), "y": round(float(p[1])), "bed": round(float(b), 1),
                           "water": round(float(w), 1)} for p, b, w in zip(points[::70], bed[::70], surface[::70])]}
    (OUT / "river-report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "samples"}, indent=2))


if __name__ == "__main__":
    main()
