"""Stage the scoped promenade palm correction without rebuilding the map or its scene.

The legacy snapshots in output/veridant/palm-terrace-v1 identify the exact published
tree faces. Retain unrelated OBJ lines byte for byte; remove only those faces and
two matching tree colliders, then append the new trunks and planting surrounds.
This records the initial migration. Furniture work subsequently split the dressing
model; the final planting lives in veridant_palm_pits.vmdl, as generated by
veridant_map.build(), and is installed by import-palm-pits.cs.txt.
"""
import hashlib
import json
import re
from collections import Counter
from pathlib import Path

import numpy as np

import map_kit as K
import veridant_map as V
import veridant_parts as P
import veridant_materials as M

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "output/veridant/palm-terrace-v1"
STAGE = WORK / "stage-v1"
MODEL = Path("Assets/models/maps/veridant")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_obj(raw):
    lines = raw.decode().splitlines(keepends=True)
    vertices = [tuple(float(x) for x in line.split()[1:4]) for line in lines if line.startswith("v ")]
    counts = {kind: sum(line.startswith(kind + " ") for line in lines) for kind in ("v", "vt", "vn")}
    return lines, vertices, counts


def face_key(line, material, vertices):
    return material, tuple(sorted(vertices[int(ref.split("/")[0]) - 1] for ref in line.split()[1:]))


def lookup(path, bark_only=False):
    lines, vertices, _ = parse_obj(path.read_bytes())
    material = None
    result = Counter()
    for line in lines:
        if line.startswith("usemtl "):
            material = line.split()[1]
        elif line.startswith("f ") and (not bark_only or material == "vr_palm_bark"):
            result[face_key(line, material, vertices)] += 1
    return result


def merge_obj(original, destination, fresh, remove):
    lines, vertices, counts = parse_obj(original.read_bytes())
    retained = []
    found = Counter()
    material = None
    expected = remove.copy()
    for line in lines:
        if line.startswith("usemtl "):
            material = line.split()[1]
        if line.startswith("f "):
            key = face_key(line, material, vertices)
            if expected[key]:
                expected[key] -= 1
                found[material] += 1
                continue
        retained.append(line)
    assert not +expected, (original, sum((+expected).values()))
    kept_bytes = "".join(retained).encode()
    appended = []
    for line in fresh.read_text().splitlines():
        if line.startswith(("v ", "vt ", "vn ", "usemtl ")):
            appended.append(line)
        elif line.startswith("f "):
            refs = []
            for token in line.split()[1:]:
                a, b, c = map(int, token.split("/"))
                refs.append(f"{a+counts['v']}/{b+counts['vt']}/{c+counts['vn']}")
            appended.append("f " + " ".join(refs))
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(kept_bytes + ("\n".join(appended) + "\n").encode())
    assert destination.read_bytes().startswith(kept_bytes)
    return {"removed_faces": dict(found), "retained_bytes_sha256": hashlib.sha256(kept_bytes).hexdigest(),
            "retained_bytes": len(kept_bytes), "added_faces": sum(x.startswith("f ") for x in appended)}


def validate(model):
    for paint, polygons in model.polygons.items():
        for points, normal in polygons:
            assert np.isfinite(points).all() and np.isfinite(normal).all()
            for k in range(1, len(points) - 1):
                cross = np.cross(points[k] - points[0], points[k+1] - points[0])
                assert np.linalg.norm(cross) > 1e-7, (paint, points)
                assert np.dot(cross, normal) > 0, (paint, points)
    assert not model.boxes and not model.hulls


def main():
    STAGE.mkdir(parents=True, exist_ok=True)
    placements = json.loads((WORK / "legacy-placements.json").read_text())
    assert len(placements) == 17
    removed = [p for p in placements if p["seed"] in (202, 203)]
    retained = [p for p in placements if p["seed"] not in (202, 203)]
    assert len(removed) == 2 and len(retained) == 15
    files = {}

    def record(relative, staged):
        original = ROOT / relative
        before = sha(original) if original.exists() else None
        if before == sha(staged):
            return
        backup = STAGE / "before" / relative
        if before:
            backup.parent.mkdir(parents=True, exist_ok=True)
            if backup.exists():
                assert sha(backup) == before, ("Original changed since stage", relative)
            else:
                backup.write_bytes(original.read_bytes())
        files[relative.as_posix()] = {"before": before, "after": sha(staged),
            "source": staged.relative_to(ROOT).as_posix(),
            "backup": backup.relative_to(ROOT).as_posix() if before else None}

    inputs = {p: sha(ROOT/p) for p in ("Tools/veridant_map.py", "Tools/veridant_parts.py",
        "Tools/veridant_materials.py", "Tools/veridant_palm_terrace.py", "Tools/map_kit.py")}
    protect = ["Assets/scenes/maps/Veridant/veridant.scene",
        "Assets/models/maps/veridant/veridant_foliage.vmdl",
        "Assets/models/maps/veridant/veridant_foliage.mtl",
        "Assets/models/maps/veridant/veridant_ground.obj",
        "Assets/models/maps/veridant/veridant_ground.vmdl",
        "Assets/models/maps/veridant/veridant_buildings.obj",
        "Assets/models/maps/veridant/veridant_buildings.vmdl"]
    protect += [p.relative_to(ROOT).as_posix() for p in (ROOT/MODEL).glob("*_hulls_*.obj")]
    protected = {p: sha(ROOT/p) for p in protect}
    trunks, pits = K.Model(), K.Model()
    for p in retained:
        P.palm_trunk(trunks, p["base"], p["h"], p["seed"], p["lean"])
        if p["base"][2] == 0:
            P.palm_pit(pits, p["base"], p["seed"])
    validate(trunks)
    validate(pits)
    for model in (trunks, pits):
        V.configure(model)
    K.write_obj(WORK/"fresh-trunks.obj", trunks, "veridant_foliage")
    K.write_obj(WORK/"fresh-pits.obj", pits, "veridant_dress")
    # The removed trees' bark is already included in the all-trunk lookup.
    removal = lookup(WORK/"legacy-palms.obj", bark_only=True)
    for key, count in lookup(WORK/"removed-palms.obj").items():
        if key[0] != "vr_palm_bark":
            removal[key] += count
    assert sum(n for k, n in removal.items() if k[0] == "vr_palm_bark") == 17*120
    foliage = MODEL / "veridant_foliage.obj"
    foliage_result = merge_obj(ROOT/foliage, STAGE/foliage, WORK/"fresh-trunks.obj", removal)
    record(foliage, STAGE/foliage)
    dress = MODEL / "veridant_dress.obj"
    dress_result = merge_obj(ROOT/dress, STAGE/dress, WORK/"fresh-pits.obj", Counter())
    record(dress, STAGE/dress)
    mtl = dress.with_suffix(".mtl")
    used = set(pits.polygons)
    existing = set(re.findall(r"^newmtl (\S+)", (ROOT/mtl).read_text(), re.M))
    updated_mtl = (ROOT/mtl).read_bytes() + b"\n" + "".join(f"newmtl {p}\nKd 1 1 1\nd 1\n" for p in sorted(used-existing)).encode()
    (STAGE/mtl).write_bytes(updated_mtl)
    record(mtl, STAGE/mtl)
    vmdl = dress.with_suffix(".vmdl")
    original = (ROOT/vmdl).read_bytes().decode()
    blocks = list(re.finditer(r'\{\s*_class = "PhysicsShapeBox"[^{}]*\}', original))
    deleted = []
    for block in blocks:
        body = block.group()
        if 'surface_prop = "wood"' not in body:
            continue
        position = re.search(r"origin = \[ ([^\]]+) \]", body)
        size = re.search(r"dimensions = \[ ([^\]]+) \]", body)
        if position and size:
            xyz = tuple(float(x) for x in position[1].split(","))
            whd = tuple(float(x) for x in size[1].split(","))
            if xyz in ((-240., 900., 150.), (180., 900., 150.)) and whd == (24., 24., 300.):
                deleted.append(block)
    assert len(deleted) == 2, len(deleted)
    updated = original
    for block in reversed(deleted):
        a, b = block.span()
        if updated[b:b+1] == ",":
            b += 1
        updated = updated[:a] + updated[b:]
    # Add only the new pit material; existing remaps and remaining physics stay exact.
    at = updated.index("[", updated.index("remaps =")) + 1
    remaps = "".join(f'\n{{ from = "{paint}.vmat" to = "materials/veridant/{paint}.vmat" }},'
                    for paint in sorted(used) if f'from = "{paint}.vmat"' not in updated)
    updated = updated[:at] + remaps + updated[at:]
    assert updated.count('_class = "PhysicsShapeBox"') == original.count('_class = "PhysicsShapeBox"') - 2
    (STAGE/vmdl).write_bytes(updated.encode())
    record(vmdl, STAGE/vmdl)
    materials = Path("Assets/materials/veridant")
    out = STAGE/materials
    out.mkdir(parents=True, exist_ok=True)
    M.build("vr_palm_bark", out)
    for name in ("vr_palm_bark_color.jpg", "vr_palm_bark_normal.jpg", "vr_palm_bark_rough.png", "vr_palm_bark.vmat"):
        record(materials/name, out/name)
    mulch = out/"vr_palm_mulch.vmat"
    mulch.write_text(M.vmat("materials/veridant/vr_gravel_color.jpg", "materials/veridant/vr_gravel_normal.jpg",
                            "materials/veridant/vr_gravel_rough.png", tint=M.DERIVED["vr_palm_mulch"][1]))
    record(materials/mulch.name, mulch)
    result = {"revision": "veridant-palm-terrace-v1", "files": files, "source_sha256": inputs,
        "protected_sha256": protected, "removed_palms": removed, "retained_palms": retained,
        "trunks_rebuilt": len(retained), "pits_added": sum(p["base"][2] == 0 for p in retained),
        "colliders_removed": 2, "foliage": foliage_result, "dress": dress_result,
        "scene_changed": False, "retained_crowns_changed": False}
    for group in (inputs, protected):
        for path, expected in group.items():
            assert sha(ROOT/path) == expected, ("Shared input changed", path)
    for path, spec in files.items():
        assert (sha(ROOT/path) if (ROOT/path).exists() else None) == spec["before"], ("Shared target changed", path)
    (STAGE/"manifest.json").write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps({"files": len(files), "trunks_rebuilt": 15, "pits_added": result["pits_added"],
        "colliders_removed": 2, "foliage": foliage_result, "dress": dress_result}))


if __name__ == "__main__":
    main()
