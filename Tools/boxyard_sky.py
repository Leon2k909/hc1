"""Boxyard's own clear midday sky, using the existing HDR atmosphere pipeline.

Stages source assets for native editor import; it does not touch Assets directly.
The sky and map read the same sun angles and light colour from map_daylight.
"""
import argparse
import json
import math
import os
from pathlib import Path

os.environ.setdefault("NUMBA_NUM_THREADS", "4")
os.environ.setdefault("OMP_NUM_THREADS", "4")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "4")

import numpy as np
from PIL import Image
import belltower_sky as S
from map_daylight import PROFILES

ROOT = Path(__file__).resolve().parent.parent
RESOURCE = "materials/boxyard/sky"
NAME = "boxyard_midday"
PROFILE = PROFILES["Boxyard"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "output/map-daylight-20261017/sky-stage")
    parser.add_argument("--width", type=int, default=4096)
    args = parser.parse_args()
    if args.width < 1024 or args.width > 8192 or args.width & (args.width - 1):
        parser.error("--width must be a power of two from 1024 to 8192")
    args.out.mkdir(parents=True, exist_ok=True)
    S.SUN_PITCH, S.SUN_YAW = PROFILE["sun_angles"][:2]
    S.LIGHT = np.array([float(x) for x in PROFILE["components"]["DirectionalLight"]["LightColor"].split(",")[:3]])
    S.SKY_KEYS = ((0, (210, 225, 236)), (6, (190, 215, 235)), (15, (166, 201, 232)),
                  (30, (137, 180, 224)), (55, (111, 161, 215)), (90, (102, 153, 210)))
    S.SUN_HALO = 0.35
    S.HALO_WHITE = np.array((1.02, 1.0, 0.96))
    sun = S.sun_direction()
    base = S.clear_sky_base(1024, 512, sun)
    directions = S.panorama_directions(args.width, args.width // 2)
    sky = S.clear_sky_at(directions, base, sun).astype(np.float32)
    # Replace the legacy broad disk with a physical-sized 0.53-degree solar disk.
    cosine = directions @ sun
    legacy = np.power(np.clip(cosine + 0.00025, 0, None), 10000.0) * 10 * np.clip(directions[..., 2], 0, 1)
    disk = S.smoothstep(math.cos(math.radians(0.30)), math.cos(math.radians(0.23)), cosine)
    sky += (disk * 24 - legacy)[..., None] * S.LIGHT
    sky = np.maximum(sky, 0)
    if not np.isfinite(sky).all():
        raise ValueError("Non-finite sky radiance")
    S.write_exr(args.out / f"{NAME}.exr", sky.astype(np.float32))
    material = f'''// Generated by Tools/boxyard_sky.py
"Layer0"
{{
    shader "shaders/sky.shader"
    F_TEXTURE_FORMAT2 "6"
    g_flBrightnessExposureBias "0"
    g_flRenderOnlyExposureBias "0"
    SkyTexture "{RESOURCE}/{NAME}.exr"
}}
'''
    (args.out / f"{NAME}.vmat").write_text(material, encoding="utf-8", newline="\n")
    Image.fromarray(S.display(sky[::2, ::2])).save(args.out / "panorama-preview.png")
    summary = {"sun_angles": PROFILE["sun_angles"], "sun_direction": sun.tolist(),
               "dimensions": [args.width, args.width // 2], "finite": True,
               "resource": f"{RESOURCE}/{NAME}.vmat",
               "minimum_radiance": float(sky.min()), "maximum_radiance": float(sky.max())}
    (args.out / "sky-validation.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary), flush=True)


if __name__ == "__main__":
    main()

