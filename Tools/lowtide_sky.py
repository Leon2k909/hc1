"""Lowtide's drifting coastal sky. Run: python Tools/lowtide_sky.py [--size 1024].

The photographic cloud layer is kept in Tools/lowtide_clouds_source.png; its
ImageGen prompt is recorded in Tools/lowtide_sky_imagegen.json. Prepare the source
as a power-of-two RGBA texture without changing its colour or transparency.

A separate periodic noise field adds thin, high, wind-stretched clouds. The
shader projects both layers at altitude and translates them in metres/second.
The HDR background and sun stay fixed. A small component updates one time uniform
because the editor's sky pass freezes the normal shader clock. No cloud meshes,
particles or runtime volume ray march. Regenerating the map keeps this material.
"""
import argparse
import json
import math
import time
import uuid
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

import belltower_sky as S

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Assets/materials/lowtide/sky"
RESOURCE = "materials/lowtide/sky"
MATERIAL = f"{RESOURCE}/lowtide_sky.vmat"
TILE, ALTITUDE = 8000.0, 1550.0
WIND = (7.8, -10.4)  # north/west in world x/y; 13 m/s aloft, same heading as WorldWind
RADIANCE = 0.70
SUN_PITCH, SUN_YAW = 38.0, -15.0


def meta(path):
    p = path.with_name(path.name + ".meta")
    if not p.exists():
        ident = uuid.uuid5(uuid.NAMESPACE_URL, "hc1/" + str(path.relative_to(ROOT)).replace("\\", "/"))
        p.write_text(json.dumps({"guid": str(ident)}, indent=2) + "\n", encoding="utf-8")


def periodic_noise(rng, shape, cells):
    """Cubic noise on a periodic lattice, including the interpolation at the tile seam."""
    grid = rng.normal(size=cells).astype(np.float32)
    coords = np.meshgrid(*(np.arange(n, dtype=np.float32) * c / n for n, c in zip(shape, cells)), indexing="ij")
    a = ndimage.map_coordinates(grid, coords, order=3, mode="grid-wrap")
    return a / max(float(a.std()), 1e-6)


def bake_high_clouds(size, seed=41):
    rng = np.random.default_rng(seed)
    shape = (size, size)
    broad = periodic_noise(rng, shape, (7, 7))
    trails = (0.63 * periodic_noise(rng, shape, (11, 58))
              + 0.25 * periodic_noise(rng, shape, (24, 112))
              + 0.12 * periodic_noise(rng, shape, (48, 223)))
    return np.clip(np.rint(S.smoothstep(0.4, 2.2, trails + broad * 0.5) * 255), 0, 255).astype(np.uint8)


def clear_sky():
    # Match Lowtide's existing warm light, with a less saturated marine blue.
    S.SUN_PITCH, S.SUN_YAW = SUN_PITCH, SUN_YAW
    S.LIGHT = np.array((1.32, 1.08, 0.82))
    S.SKY_KEYS = ((0, (209, 222, 232)), (6, (185, 208, 226)), (15, (155, 190, 220)),
                  (30, (126, 174, 212)), (55, (101, 156, 201)), (90, (88, 144, 190)))
    sun = S.sun_direction()
    dirs = S.panorama_directions(2048, 1024)
    base = S.clear_sky_base(1024, 512, sun)
    u, v = S.panorama_uv(dirs)
    coords = (np.clip(v * 512 - 0.5, 0, 511), u * 1024 - 0.5)
    sky = np.stack([ndimage.map_coordinates(base[..., c], coords, order=1, mode="grid-wrap") for c in range(3)], -1)
    # A 0.53-degree sun with a small soft aureole, rather than the old oversized blob.
    cos = dirs @ sun
    disk = S.smoothstep(math.cos(math.radians(0.30)), math.cos(math.radians(0.23)), cos)
    sky += disk[..., None] * S.LIGHT * 18
    below = S.smoothstep(0, -0.12, np.arcsin(np.clip(dirs[..., 2], -1, 1)))[..., None]
    return (sky * (1 - below) + S.GROUND * below).astype(np.float32)


def material_text():
    return f'''// Generated by Tools/lowtide_sky.py
"Layer0"
{{
    shader "shaders/hc1_coastal_sky.shader"
    SkyTexture "{RESOURCE}/lowtide_clear.exr"
    Clouds "{RESOURCE}/lowtide_clouds_photo.png"
    HighClouds "{RESOURCE}/lowtide_high_clouds.png"
    g_flCloudAltitude "{ALTITUDE}"
    g_flCloudTile "{TILE}"
    g_vCloudWind "{WIND[0]} {WIND[1]} 0 0"
    g_flCloudRadiance "{RADIANCE}"
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, default=1024)
    args = parser.parse_args()
    if args.size < 256 or args.size > 4096 or args.size & (args.size - 1):
        parser.error("--size must be a power of two between 256 and 4096")
    start = time.time()
    OUT.mkdir(parents=True, exist_ok=True)
    source = ROOT / "Tools/lowtide_clouds_source.png"
    if not source.exists():
        parser.error(f"Missing photographic source: {source}")
    clouds = Image.open(source).convert("RGBA").resize((args.size, args.size), Image.Resampling.LANCZOS)
    clouds = np.array(clouds)
    # Publish complete files so the editor never reads half of a texture.
    for name, data in (("lowtide_clouds_photo.png", clouds), ("lowtide_high_clouds.png", bake_high_clouds(args.size))):
        temp = OUT / (name + ".writing")
        Image.fromarray(data).save(temp, format="PNG")
        temp.replace(OUT / name)
    temp = OUT / "lowtide_clear.exr.writing"
    S.write_exr(temp, clear_sky())
    temp.replace(OUT / "lowtide_clear.exr")
    temp = OUT / "lowtide_sky.vmat.writing"
    temp.write_text(material_text(), encoding="utf-8", newline="\n")
    temp.replace(OUT / "lowtide_sky.vmat")
    for file in OUT.iterdir():
        if file.suffix in (".png", ".exr", ".vmat"):
            meta(file)
    print(f"Baked Lowtide sky in {time.time() - start:.1f}s; {np.mean(clouds[..., 3] > 128) * 100:.1f}% cloud cover")


if __name__ == "__main__":
    main()
