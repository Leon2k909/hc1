def equipment():
    prefab = copy.deepcopy(json.loads((ASSETS / "prefabs/gunsmith/charms/charm_sbox.prefab").read_text(encoding="utf-8")))
    def remap(node):
        if isinstance(node, dict):
            if "__guid" in node:
                node["__guid"] = str(uuid.uuid5(uuid.NAMESPACE_URL, "hc1/pocket-scout/prefab/" + node["__guid"]))
            for value in node.values():
                remap(value)
        elif isinstance(node, list):
            for value in node:
                remap(value)
    remap(prefab)
    root = prefab["RootObject"]
    root["Name"] = "charm_pocket_scout"
    charm = next(c for c in root["Children"] if c["Name"] == "Charm")
    charm["Name"] = "Pocket Scout Pendant"
    for component in charm["Components"]:
        if component["__type"] == "Sandbox.ModelRenderer":
            component["Model"] = f"{BASE}/{NAME}.vmdl"
        elif component["__type"] == "JiggleBone":
            component["EndPoint"] = "0,0,-0.8"
            component["Mass"] = .9
    write_json(ASSETS / "prefabs/gunsmith/charms/charm_pocket_scout.prefab", prefab)
    write_json(ASSETS / "gunsmith/charms/charm_pocket_scout.gnsmth", {
        "Name": "Pocket Scout", "Description": "A miniature nano scout drone on a brass hanging loop.",
        "Category": "Charm", "MainPrefab": {"_type": "gameobject", "prefab": "prefabs/gunsmith/charms/charm_pocket_scout.prefab"},
        "EligibleEquipment": [], "RequiredLevel": 0, "__references": [], "IsValid": True, "__version": 0
    })
    for folder in [OUT, ASSETS / "prefabs/gunsmith/charms", ASSETS / "gunsmith/charms"]:
        for path in folder.iterdir():
            if path.suffix in (".obj", ".mtl", ".vmdl", ".vmat", ".png", ".prefab", ".gnsmth") and (
                    folder == OUT or path.stem == "charm_pocket_scout"):
                metadata(path)


def preview(obj):
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.samples = 48
    scene.cycles.use_denoising = True
    scene.render.resolution_x, scene.render.resolution_y = 1000, 800
    scene.render.resolution_percentage = 100
    scene.world.use_nodes = True
    scene.world.node_tree.nodes["Background"].inputs["Color"].default_value = (.24, .27, .31, 1)
    scene.world.node_tree.nodes["Background"].inputs["Strength"].default_value = .5
    for name, position, energy, size in [("Key", (1, -2, 3), 130, 2), ("Rim", (-2, 1, 2), 160, 2),
                                         ("Fill", (2, 2, 1), 65, 2)]:
        data = bpy.data.lights.new(name, "AREA")
        data.energy, data.shape, data.size = energy, "DISK", size
        light = bpy.data.objects.new(name, data)
        scene.collection.objects.link(light)
        light.location = position
        light.rotation_euler = (Vector((-.2, 0, -.45)) - light.location).to_track_quat("-Z", "Y").to_euler()
    data = bpy.data.cameras.new("Buddy preview")
    data.type, data.ortho_scale = "ORTHO", 1.75
    camera = bpy.data.objects.new("Buddy preview", data)
    scene.collection.objects.link(camera)
    scene.camera = camera
    for label, position in [("three_quarter", (1.8, -3.5, 1.3)), ("side", (0, -4, -.4))]:
        camera.location = position
        camera.rotation_euler = (Vector((-.2, 0, -.45)) - camera.location).to_track_quat("-Z", "Y").to_euler()
        scene.render.filepath = str(PREVIEW / f"{label}.png")
        bpy.ops.render.render(write_still=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(PREVIEW / "pocket_scout.blend"), relative_remap=True)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    PREVIEW.mkdir(parents=True, exist_ok=True)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    atlas, brass = materials()
    info = {}
    objects = []
    for lod in range(3):
        obj = build_lod(lod, atlas, brass)
        objects.append(obj)
        info[f"lod{lod}"] = export_mesh(obj, OUT / f"{NAME}_lod{lod}.obj")
        obj.hide_render = obj.hide_viewport = lod > 0
    assert info["lod0"]["triangles"] > info["lod1"]["triangles"] > info["lod2"]["triangles"]
    modeldoc()
    equipment()
    write_json(PREVIEW / "asset-info.json", {"units": "inches; X forward, Y left, Z up", **info})
    preview(objects[0])
    print("POCKET_SCOUT_READY " + json.dumps(info))


if __name__ == "__main__":
    main()
